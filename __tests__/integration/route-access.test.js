// REARCH-04: every route's first middleware declares who may call it (middleware/access.js),
// and the whole table is committed as docs/routes.md.
//
// The table is the review signal. A route that opens, or a `superadmin` that becomes
// `member`, shows as a one-line diff in a file whose only purpose is to be read — the signal
// that did not exist for GET /player/:id, which served decrypted contact details to anyone
// for years because "no gate" is the absence of a line.
//
// After adding or changing a route: UPDATE_ROUTE_TABLE=1 npx jest route-access

const fs = require('fs');
const path = require('path');
const { routeTable } = require('../helpers/routeTable');
const app = require('../../app');

const TABLE_FILE = path.join(__dirname, '..', '..', 'docs', 'routes.md');
const table = routeTable(app);

function render(rows) {
  const lines = [
    '# Routes',
    '',
    'Generated by `__tests__/integration/route-access.test.js` — do not edit by hand. After',
    'adding or changing a route: `UPDATE_ROUTE_TABLE=1 npx jest route-access`.',
    '',
    'Every route, in registration order (first match wins), with the `access.*` declaration',
    'that is its first middleware. See `middleware/access.js` for what each level means.',
    '',
    '| # | Method | Path | Access |',
    '|---:|---|---|---|',
  ];
  for (const r of rows) {
    lines.push(`| ${r.order} | ${r.method} | \`${r.path.replace(/\|/g, '\\|')}\` | ${r.access || '**none**'} |`);
  }
  return lines.join('\n') + '\n';
}

it('finds the whole route table, including the routes app.js registers itself', () => {
  expect(table.length).toBeGreaterThanOrEqual(210);
  const keys = table.map(r => r.method + ' ' + r.path);
  expect(keys).toContain('GET /health');
  expect(keys).toContain('GET /tables/:division');
  expect(keys).toContain('POST /scorecard-beta');
});

it('gives every route exactly one declaration, as its first middleware', () => {
  const bad = table.filter(r => !r.access || r.misplaced || r.declarations > 1)
    .map(r => `${r.method} ${r.path}: ` +
      (!r.access && !r.misplaced ? 'no access.* declaration' :
        r.misplaced ? 'access.* is not the first middleware' : `${r.declarations} declarations`));
  expect(bad).toEqual([]);
});

it('matches docs/routes.md', () => {
  const rendered = render(table);
  if (process.env.UPDATE_ROUTE_TABLE) fs.writeFileSync(TABLE_FILE, rendered);
  const committed = fs.existsSync(TABLE_FILE) ? fs.readFileSync(TABLE_FILE, 'utf8') : '';
  // On a mismatch, regenerate (see the top of this file) and read the diff before committing.
  expect(committed).toBe(rendered);
});
